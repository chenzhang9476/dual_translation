#!/usr/bin/env python3
"""Generate a deterministic Markdown inventory for the current release."""

from __future__ import annotations

from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PROJECT_ROOT / "FILE_INDEX.md"
SKIP_PARTS = {".git", "__pycache__", ".venv"}
SKIP_FILES = {"FILE_INDEX.md"}


def purpose(path: Path) -> str:
    suffix = path.suffix.lower()
    if path.name == "README.md":
        return "Directory documentation."
    if path.name == "UPSTREAM_README.md":
        return "Original upstream documentation."
    if suffix == ".py":
        return "Python source or executable utility."
    if suffix in {".yml", ".yaml", ".toml", ".conf", ".cfg", ".ini"}:
        return "Configuration file."
    if suffix in {".csv", ".json"}:
        return "Configuration, split metadata, index, or tabular output."
    if suffix in {".sh"}:
        return "Shell helper."
    if suffix in {".pth", ".pt", ".ckpt"}:
        return "Trained model checkpoint."
    if suffix in {".png", ".jpg", ".jpeg"}:
        return "Retained visualization artifact."
    if suffix in {".nii", ".gz"}:
        return "Medical image or compressed artifact."
    return "Project support file."


def main() -> None:
    files = []
    for path in PROJECT_ROOT.rglob("*"):
        if not path.is_file() or path.name in SKIP_FILES:
            continue
        relative = path.relative_to(PROJECT_ROOT)
        if any(part in SKIP_PARTS for part in relative.parts):
            continue
        files.append(relative)

    lines = [
        "# File Index",
        "",
        "Generated by `tools/generate_file_index.py`.",
        "",
        "| Path | Purpose |",
        "|---|---|",
    ]
    for relative in sorted(files, key=lambda item: item.as_posix().lower()):
        lines.append(f"| `{relative.as_posix()}` | {purpose(relative)} |")
    lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT} with {len(files)} entries")


if __name__ == "__main__":
    main()
